/** The current library profile for an exercise id, as a fresh copy, or undefined if the library has no such exercise. */
export function findExerciseProfile(id: string): ExerciseLibraryProfile | undefined {
  const profile = (EXERCISE_PROFILES as Record<string, ExerciseLibraryProfile | undefined>)[id];
  if (!profile) return undefined;
  return {
    ...profile,
    equipmentNeeded: [...profile.equipmentNeeded],
    incrementOptions: [...profile.incrementOptions],
    lightAlternativeIds: [...profile.lightAlternativeIds],
    jointStressTags: [...profile.jointStressTags],
    cues: { setup: profile.cues.setup, form: [...profile.cues.form] },
  };
}
