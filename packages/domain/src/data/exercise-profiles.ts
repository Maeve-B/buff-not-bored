/**
 * The v2 library profile (PRODUCT_SPEC.md v2 §9.1) for every exercise in
 * data/exercises.ts, keyed by exercise id. Kept as its own table so the
 * re-tag can be reviewed in one place (DECISIONS.md D-005); exercises.ts
 * merges it in, and a missing profile fails at module load.
 *
 * Conventions:
 * - `station` follows the v1 `location` (rack → rack, bench → bench,
 *   standing → open_space, floor and bench_or_floor → floor), so faff
 *   scoring sees the same layout as before.
 * - Increments start at 0.25 kg so small jumps are always available
 *   (D-007): barbell [0.25, 0.5, 1, 2.5, 5] kg, dumbbells [0.25, 0.5, 1, 2,
 *   2.5] kg. Unloaded bodyweight has none.
 * - Default progression: compound → load_nudge, isolation →
 *   double_progression, unloaded bodyweight → ladder (§6.5).
 * - Light alternatives must share the movement pattern (§6.6) and are empty
 *   where the v1 library has no suitable variant yet (Phase 1 adds them).
 * - Cable and machine stacks use the barbell jumps (STACK), so 0.25 kg
 *   add-on plates are always offered (D-007).
 * - Assisted exercises have no light alternative: their lighter version is
 *   the same exercise with more assistance. They get swap groups of their
 *   own, because assistance and load move in opposite directions.
 * - Light alternatives may point anywhere in the library (D-022): Circuit's
 *   swaps and refreshes still draw only on the classic 33 (CLASSIC_EXERCISES).
 * - The pull-up ladder (§10.3) is linked with regressionId / progressionId:
 *   dead hang → scapular pull-up → band- or machine-assisted pull-up →
 *   negative → pull-up. Stage 3 is "band or machine", so both regress to
 *   the scapular pull-up; its single progressionId names the band version.
 * - Assisted pull-ups (band or machine) have swap groups of their own: they
 *   aren't an equivalent stimulus to a full pull-up.
 * - Dead hang and scapular pull-up are filed under vertical pull (no "hang"
 *   pattern in §9.1) as isolation work; pattern coverage counts only
 *   compound exercises (S-011).
 * - Ab crunch, hanging knee raise and captain's chair are trunk flexion,
 *   filed under anti-extension (no flexion pattern in §9.1) but in their
 *   own swap group, so they're never swapped for a brace like the plank.
 * - Leg curl is filed under `hinge`: §9.1 has no knee-flexion pattern, and
 *   hinge is the closest hamstring pattern (flagged in the S-003 review).
 */

