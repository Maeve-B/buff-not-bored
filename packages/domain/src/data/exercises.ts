function withProfile(base: BaseExercise): Exercise {
  const profile = findExerciseProfile(base.id);
  if (!profile) {
    throw new Error(`Exercise "${base.id}" has no library profile in data/exercise-profiles.ts.`);
  }
  return { ...base, ...profile };
}

